import type { LayoutStubProps } from "../../types";

const ROOT_LAYOUT = {
	imports: [] as string[],
	css: "./globals.css",
	staticParams: "",
	signature: 'function RootLayout({ children }: LayoutProps<"/">)',
	setup: "",
	lang: '"en"',
};

const LOCALE_LAYOUT: typeof ROOT_LAYOUT = {
	imports: [
		'import { notFound } from "next/navigation";',
		'import { hasLocale } from "next-intl";',
		'import { setRequestLocale } from "next-intl/server";',
		'import { routing } from "@/lib/i18n";',
	],
	css: "../globals.css",
	staticParams: `
export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}
`,
	signature: 'async function RootLayout({ children, params }: LayoutProps<"/[locale]">)',
	setup: `  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();

  setRequestLocale(locale);

`,
	lang: "{locale}",
};

export function buildLayoutStub({ fontCode, isLocalized, providers }: LayoutStubProps): string {
	const layout = isLocalized ? LOCALE_LAYOUT : ROOT_LAYOUT;
	const imports = [
		'import type { Metadata } from "next";',
		...layout.imports,
		fontCode.imports,
		...providers.map(({ name, from }) => `import { ${name} } from "${from}";`),
		`import "${layout.css}";`,
	];
	const content = providers.reduceRight(
		(inner, { name }) => `<${name}>${inner}</${name}>`,
		"{children}",
	);

	return `${imports.join("\n")}

${fontCode.declarations}

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};
${layout.staticParams}
export default ${layout.signature} {
${layout.setup}  return (
    <html
      lang=${layout.lang}
      className={\`${fontCode.classNames} h-full antialiased\`}
    >
      <body className="min-h-full flex flex-col">${content}</body>
    </html>
  );
}
`;
}
